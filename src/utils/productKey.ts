// Ключ сопоставления товаров — одна точка на всё приложение.
//
// Раньше каждый экран сравнивал названия по-своему: в категории точной
// строкой (даже без регистра), в товаре точным совпадением, в покупках через
// lower(). Из-за этого «Молоко» и «молоко» уже расходились в разные записи,
// а «Куриное филе» и «Филе куриное» тем более.
//
// Отображается всегда исходное cleaned_name; этот ключ нужен только для
// группировки и поиска.

/**
 * Что схлопывается: регистр, ё/е, пунктуация («Lay's» = «Lays»,
 * «Кока-кола» = «Кока кола»), лишние пробелы и порядок слов
 * («Филе куриное» = «Куриное филе»).
 *
 * Что НЕ схлопывается: цифры и проценты. «Молоко 3.2%» и «Молоко 1.5%» —
 * разные товары с разной ценой, их слипание испортило бы и историю цен, и
 * аналитику. Разделитель дроби при этом убирается, поэтому «3.2%» и «3,2%»
 * дают один ключ.
 */
export function productKey(name: string): string {
  return (name ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    // Апостроф удаляется, а не заменяется пробелом: иначе «Lay's» распадается
    // на «lay» + «s» и перестаёт совпадать с «Lays».
    .replace(/['’‘`]/g, '')
    .replace(/(\d)[.,](\d)/g, '$1$2')
    .replace(/[^a-z0-9а-я%]+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
    .sort()
    .join(' ');
}

/**
 * Из нескольких написаний одного товара выбирает то, что показывать.
 * Берём самое частое, при равенстве — самое длинное: развёрнутое
 * «Куриное филе охлаждённое» информативнее обрезанного «Филе».
 */
export function preferredDisplayName(variants: string[]): string {
  const counts = new Map<string, number>();
  for (const variant of variants) {
    const trimmed = variant.trim();
    if (trimmed) counts.set(trimmed, (counts.get(trimmed) ?? 0) + 1);
  }

  let best = '';
  let bestCount = 0;
  for (const [name, count] of counts) {
    if (count > bestCount || (count === bestCount && name.length > best.length)) {
      best = name;
      bestCount = count;
    }
  }
  return best;
}
