// Адреса юридических документов. Apple и Google требуют, чтобы с экрана
// подписки вели рабочие ссылки на условия использования и политику
// конфиденциальности — нерабочая ссылка это отказ на ревью.
//
// Тексты лежат в репозитории (docs/), но магазинам нужен публичный URL.
// Перед отправкой в сторы опубликуйте документы (например, GitHub Pages)
// и подставьте сюда настоящие адреса — это единственное место, где они
// заданы.
//
// Если адрес оставить пустым, ссылка на экране просто не отрисуется:
// лучше её отсутствие, чем кнопка, ведущая в никуда.

export const LEGAL_URLS = {
  privacy: '',
  terms: '',
} as const;

export function hasLegalLinks() {
  return Boolean(LEGAL_URLS.privacy && LEGAL_URLS.terms);
}
